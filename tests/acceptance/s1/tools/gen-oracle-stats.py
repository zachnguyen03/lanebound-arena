#!/usr/bin/env python3
"""Mechanically extracts the §7 L1/L7/L10 stat tables from the build spec into _oracle-stats.ts.
Usage: python3 tools/gen-oracle-stats.py /path/to/lanebound-arena-build-spec-v1.md > _oracle-stats.ts
The spec is the only input. Never run this against kits.ts or sim code."""
import re, sys, json
spec = open(sys.argv[1], encoding="utf-8").read().split("\n")
out = {}; cur = None; cls = {}
for i, line in enumerate(spec, 1):
    m = re.match(r"### 7\.(\d+) (\w+)$", line)
    if m: cur = m.group(2).lower(); out[cur] = {"spec_line": i, "rows": {}}; continue
    m = re.match(r"\*\*Position / class / lean / faction:\*\* (\w+) / (\w+) /", line)
    if m and cur: out[cur]["slot"] = m.group(1); out[cur]["class"] = m.group(2)
    if cur and re.match(r"\| (1|7|10) \|", line):
        c = [x.strip() for x in line.strip("|").split("|")]
        lv = int(c[0])
        if str(lv) in out[cur]["rows"]: continue
        f = lambda s: float(s.replace("%", ""))
        out[cur]["rows"][str(lv)] = dict(line=i, hp=f(c[1]), regen=f(c[2]), atk=f(c[3]), pow=f(c[4]), pres=f(c[5]), mres=f(c[6]),
            as_=f(c[7]), crit=f(c[8]) / 100.0, range=f(c[9]), ms=f(c[10]), ehp_avg=f(c[11]))
print("// GENERATED by tools/gen-oracle-stats.py from the build spec §7 tables. Do not edit by hand.")
print("export interface SpecRow { line: number; hp: number; regen: number; atk: number; pow: number; pres: number; mres: number; as_: number; crit: number; range: number; ms: number; ehp_avg: number }")
print("export const SPEC_STATS: Record<string, { spec_line: number; slot: string; class: string; rows: Record<'1'|'7'|'10', SpecRow> }> = " + json.dumps(out, indent=1) + " as any;")
